-- Oracle DDL: Student Performance and Attendance Dashboard
-- Target: Oracle Database 12c+ (IDENTITY columns).
-- Grain: one marks row and one attendance summary row per student/subject/term.

CREATE TABLE dim_student (
    student_key NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id VARCHAR2(20) NOT NULL UNIQUE,
    student_name VARCHAR2(120) NOT NULL,
    department VARCHAR2(30) DEFAULT 'UNKNOWN' NOT NULL,
    semester NUMBER(2) NOT NULL CHECK (semester > 0),
    section VARCHAR2(10) NOT NULL
);

CREATE TABLE dim_subject (
    subject_key NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    subject_id VARCHAR2(20) NOT NULL UNIQUE,
    subject_name VARCHAR2(120) NOT NULL,
    subject_code VARCHAR2(30) NOT NULL UNIQUE,
    maximum_marks NUMBER(6,2) NOT NULL CHECK (maximum_marks > 0),
    passing_marks NUMBER(6,2) NOT NULL,
    CONSTRAINT ck_subject_pass CHECK (passing_marks >= 0 AND passing_marks <= maximum_marks)
);

CREATE TABLE dim_academic_term (
    term_key NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    term_id VARCHAR2(30) NOT NULL UNIQUE,
    academic_year VARCHAR2(20) NOT NULL,
    semester_label VARCHAR2(20) NOT NULL,
    start_date DATE NOT NULL,
    end_date DATE NOT NULL,
    CONSTRAINT ck_term_dates CHECK (end_date >= start_date)
);

CREATE TABLE dim_business_rule (
    rule_key VARCHAR2(50) PRIMARY KEY,
    numeric_value NUMBER(10,2) NOT NULL,
    description VARCHAR2(250) NOT NULL
);

CREATE TABLE dim_grade_band (
    grade_code VARCHAR2(5) PRIMARY KEY,
    minimum_score NUMBER(5,2) NOT NULL UNIQUE CHECK (minimum_score BETWEEN 0 AND 100)
);

CREATE TABLE dim_date (
    date_key NUMBER(8) PRIMARY KEY,
    calendar_date DATE NOT NULL UNIQUE,
    calendar_year NUMBER(4) NOT NULL,
    calendar_quarter NUMBER(1) NOT NULL CHECK (calendar_quarter BETWEEN 1 AND 4),
    calendar_month NUMBER(2) NOT NULL CHECK (calendar_month BETWEEN 1 AND 12),
    month_name VARCHAR2(12) NOT NULL,
    day_of_month NUMBER(2) NOT NULL CHECK (day_of_month BETWEEN 1 AND 31)
);

CREATE TABLE fact_marks (
    marks_fact_key NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_marks_id VARCHAR2(30) NOT NULL UNIQUE,
    student_key NUMBER NOT NULL REFERENCES dim_student(student_key),
    subject_key NUMBER NOT NULL REFERENCES dim_subject(subject_key),
    term_key NUMBER NOT NULL REFERENCES dim_academic_term(term_key),
    internal_marks NUMBER(6,2),
    external_marks NUMBER(6,2),
    total_marks NUMBER(6,2),
    grade VARCHAR2(5),
    result VARCHAR2(10) NOT NULL,
    record_status VARCHAR2(10) NOT NULL,
    CONSTRAINT ck_marks_status CHECK (record_status IN ('PRESENT','ABSENT','MISSING')),
    CONSTRAINT ck_marks_result CHECK (result IN ('PASS','FAIL','ABSENT','MISSING')),
    CONSTRAINT ck_marks_nonnegative CHECK (
      (internal_marks IS NULL OR internal_marks >= 0) AND
      (external_marks IS NULL OR external_marks >= 0) AND
      (total_marks IS NULL OR total_marks >= 0)
    ),
    CONSTRAINT ck_marks_absent CHECK (
      (record_status = 'PRESENT' AND internal_marks IS NOT NULL AND external_marks IS NOT NULL
       AND total_marks IS NOT NULL AND result IN ('PASS','FAIL'))
      OR (record_status = 'ABSENT' AND total_marks IS NULL AND result = 'ABSENT')
      OR (record_status = 'MISSING' AND total_marks IS NULL AND result = 'MISSING')
    ),
    CONSTRAINT uq_marks_grain UNIQUE (student_key, subject_key, term_key)
);

CREATE TABLE fact_attendance (
    attendance_fact_key NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_attendance_id VARCHAR2(30) NOT NULL UNIQUE,
    student_key NUMBER NOT NULL REFERENCES dim_student(student_key),
    subject_key NUMBER NOT NULL REFERENCES dim_subject(subject_key),
    term_key NUMBER NOT NULL REFERENCES dim_academic_term(term_key),
    total_classes NUMBER(6) NOT NULL CHECK (total_classes > 0),
    present_classes NUMBER(6) NOT NULL CHECK (present_classes >= 0),
    absent_classes NUMBER(6) NOT NULL CHECK (absent_classes >= 0),
    attendance_percentage NUMBER(5,2) NOT NULL,
    CONSTRAINT ck_attendance_counts CHECK (
      present_classes <= total_classes AND
      absent_classes = total_classes - present_classes
    ),
    CONSTRAINT ck_attendance_pct CHECK (attendance_percentage BETWEEN 0 AND 100),
    CONSTRAINT uq_attendance_grain UNIQUE (student_key, subject_key, term_key)
);

CREATE INDEX ix_fact_marks_student ON fact_marks(student_key);
CREATE INDEX ix_fact_marks_subject ON fact_marks(subject_key);
CREATE INDEX ix_fact_marks_term ON fact_marks(term_key);
CREATE INDEX ix_fact_att_student ON fact_attendance(student_key);
CREATE INDEX ix_fact_att_subject ON fact_attendance(subject_key);
CREATE INDEX ix_fact_att_term ON fact_attendance(term_key);

